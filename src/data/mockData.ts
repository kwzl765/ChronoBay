// --- Derived helpers ---

export const getProductBySlug = (slug: string): Product | undefined =>
  products.find((p) => p.slug === slug);

export const getProductsByBrand = (brandSlug: string): Product[] =>
  products.filter((p) => p.brandSlug === brandSlug);

export const getFeaturedProducts = (): Product[] =>
  products.filter((p) => p.featured);

export const getNewArrivals = (): Product[] =>
  products.filter((p) => p.newArrival);

export const getRelatedProducts = (product: Product, limit = 4): Product[] =>
  products
    .filter((p) => p.id !== product.id && (p.category === product.category || p.brandSlug === product.brandSlug))
    .slice(0, limit);

export const formatMMK = (price: number): string =>
  new Intl.NumberFormat('en-US').format(price) + ' MMK';

export const discountPercent = (product: Product): number | null => {
  if (!product.originalPrice || product.originalPrice <= product.price) return null;
  return Math.round(((product.originalPrice - product.price) / product.originalPrice) * 100);
};
